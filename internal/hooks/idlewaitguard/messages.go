// reason は理由文を組み立てる。先頭に拒否したコマンドを JSON 文字列として出し、複数行でも境界を明確にする
// （UI で理由が省略されても、先頭だけで拒否の対象を特定できる）。
func reason(label, detail, commandJSON string) string {
	return label + ": 拒否対象コマンド: " + commandJSON + "\n" + detail
}
